import type { CalculatorDef } from "./types";

/**
 * Предмет поставки в родительном падеже: «Товара» / «Оборудования».
 *
 * В претензиях слово встречается только в родительном падеже («поставка
 * Товара», «акт сдачи-приемки Товара», «частичные поставки товара») — и с
 * заглавной, и со строчной буквы, поэтому форм две. Именительный падеж нигде
 * не нужен, определения «(далее — Товар)» в шаблонах нет.
 *
 * Согласование прилагательных при замене не ломается: «Товар» мужского рода,
 * «Оборудование» среднего, но в родительном падеже единственного числа
 * окончание прилагательного у обоих одинаковое — «соответствующего». Поэтому
 * достаточно подменить само существительное, текст вокруг не трогаем.
 *
 * Если появится третий вариант («Работы», «Услуги») — дописать сюда пару,
 * во множественном числе согласование уже разъедется, тогда нужны будут
 * отдельные редакции шаблонов.
 */
const GENITIVE: Record<string, string> = {
  "Товар": "Товара",
  "Оборудование": "Оборудования",
};

export const deliverySubject: CalculatorDef = {
  id: "delivery_subject",
  inputs: ["предмет"],
  outputs: ["предмет_род", "предмет_род_строч"],
  run: (raw) => {
    const value = String(raw["предмет"] ?? "").trim();
    const genitive = GENITIVE[value];
    if (!genitive) {
      throw new Error(
        `Неизвестный предмет поставки «${value}». Допустимо: ${Object.keys(GENITIVE).join(", ")}.`,
      );
    }
    return {
      "предмет_род": genitive,
      "предмет_род_строч": genitive.toLowerCase(),
    };
  },
};
