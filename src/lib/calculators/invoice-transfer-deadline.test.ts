import { describe, expect, it } from "vitest";
import { invoiceTransferDeadline } from "./invoice-transfer-deadline";

const run = (date: string, holidays: string[] = []) =>
  invoiceTransferDeadline.run(
    { "дата_документа_приемки": date },
    { holidays: new Set(holidays) },
  )["срок_передачи_счета"];

describe("invoice_transfer_deadline", () => {
  it("7 рабочих дней от понедельника — среда следующей недели", () => {
    // пн 02.02.2026 → вт 03, ср 04, чт 05, пт 06, пн 09, вт 10, ср 11
    expect(run("2026-02-02")).toBe("11.02.2026");
  });

  it("день подписания в счёт не идёт", () => {
    // Отсчёт со следующего дня: пятница + 7 р.д. — не четверг, а пятница.
    expect(run("2026-02-06")).toBe("17.02.2026");
  });

  it("выходные пропускаются, а не считаются", () => {
    // сб 07.02.2026 → отсчёт с пн 09, седьмой рабочий — вт 17.02.
    // Совпадает с пятницей 06.02 выше: у обеих отсчёт стартует с понедельника.
    expect(run("2026-02-07")).toBe("17.02.2026");
  });

  it("праздники из календаря удлиняют срок", () => {
    const holidays = ["2026-02-04", "2026-02-05"];
    expect(run("2026-02-02", holidays)).toBe("13.02.2026");
  });

  it("без календаря праздников считает только по выходным", () => {
    expect(
      invoiceTransferDeadline.run({ "дата_документа_приемки": "2026-02-02" }),
    ).toEqual({ "срок_передачи_счета": "11.02.2026" });
  });

  it("отдаёт дату в формате дд.мм.гггг", () => {
    expect(run("2026-12-24")).toMatch(/^\d{2}\.\d{2}\.\d{4}$/);
  });

  it("переход через год", () => {
    // ср 24.12.2025 + 7 р.д., новогодние праздники не в календаре
    expect(run("2025-12-24")).toBe("02.01.2026");
  });

  it("ругается на кривой вход", () => {
    expect(() => run("24.12.2025")).toThrow(/YYYY-MM-DD/);
    expect(() => run("")).toThrow();
  });

  it("контракт inputs/outputs совпадает с реализацией", () => {
    expect(invoiceTransferDeadline.inputs).toEqual(["дата_документа_приемки"]);
    expect(invoiceTransferDeadline.outputs).toEqual(["срок_передачи_счета"]);
  });
});
