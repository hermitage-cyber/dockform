//! Удаляет «Претензионная.lnk» и «Документация.lnk» рядом с dockform.exe.
//!
//! От ярлыков отказались в v1.0.0: запуск всегда через сам `dockform.exe`,
//! раздел выбирается на первом экране. Ярлыки прокидывали `--mode=...`, из-за
//! чего экран выбора режима не показывался вовсе — а вместе с ним и индикатор
//! состояния шаблонов, который на этом экране живёт.
//!
//! Почему удаляем, а не просто перестали создавать: у пилотов, получивших
//! прошлые сборки, оба `.lnk` уже лежат в папке портабла. Они продолжали бы
//! работать и уводить мимо нового экрана. Один раз подчистить надёжнее, чем
//! просить каждого удалить файлы руками.
//!
//! Это переходный код. Когда все пилоты отработают на v1.0.0+ и старых `.lnk`
//! в папках гарантированно не останется, модуль можно выкинуть целиком вместе
//! с вызовом в `lib.rs`.
//!
//! Гейтинг тот же, что был у создания:
//! - `target_os = "windows"`: `.lnk` бывают только там;
//! - `not(debug_assertions)`: в `cargo tauri dev` бинарь лежит в `target/debug/`,
//!   портабл-папки рядом нет и чистить нечего.

#[cfg(all(target_os = "windows", not(debug_assertions)))]
pub fn remove_legacy_shortcuts() {
    let exe = match std::env::current_exe() {
        Ok(p) => p,
        Err(e) => {
            eprintln!("[shortcuts] current_exe: {e}");
            return;
        }
    };
    let Some(exe_dir) = exe.parent() else { return };

    for name in ["Претензионная", "Документация"] {
        let lnk = exe_dir.join(format!("{name}.lnk"));
        if !lnk.exists() {
            continue;
        }
        // Не блокируем запуск: не удалилось — значит файл занят или его держит
        // антивирус. Пилот в худшем случае продолжит запускать через ярлык.
        match std::fs::remove_file(&lnk) {
            Ok(()) => eprintln!("[shortcuts] удалён устаревший {name}.lnk"),
            Err(e) => eprintln!("[shortcuts] не удалось удалить {name}.lnk: {e}"),
        }
    }
}

// На macOS/Linux и в dev-сборках — no-op, чтобы не плодить `cfg` в месте вызова.
#[cfg(not(all(target_os = "windows", not(debug_assertions))))]
pub fn remove_legacy_shortcuts() {}
